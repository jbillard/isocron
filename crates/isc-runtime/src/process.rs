// the bounds of the stacks, in the thread-local storage of each thread

core::arch::global_asm!(
    ".section .tbss,\"awT\",@nobits",
    ".p2align 3",
    ".globl isc_stack_bounds",
    ".hidden isc_stack_bounds",
    ".type isc_stack_bounds,@object",
    ".size isc_stack_bounds,16",
    "isc_stack_bounds:",
    ".skip 16",
    ".text",
);

/// The lowest address and the size of the stack of the calling thread,
/// written into its thread-local storage.
fn set_stack(low: usize, size: usize) {
    // SAFETY: the 16 bytes of `isc_stack_bounds` in the thread-local storage
    // of the calling thread (the local-exec model: the thread pointer plus a
    // constant)
    unsafe {
        asm!(
            "mov qword ptr fs:[isc_stack_bounds@tpoff], {0}",
            "mov qword ptr fs:[isc_stack_bounds@tpoff + 8], {1}",
            in(reg) low,
            in(reg) size,
            options(nostack, preserves_flags)
        );
    }
}

fn own_stack() -> (usize, usize) {
    let (low, size): (usize, usize);
    // SAFETY: as `set_stack`, read
    unsafe {
        asm!(
            "mov {0}, qword ptr fs:[isc_stack_bounds@tpoff]",
            "mov {1}, qword ptr fs:[isc_stack_bounds@tpoff + 8]",
            out(reg) low,
            out(reg) size,
            options(nostack, preserves_flags, readonly)
        );
    }
    (low, size)
}

// ---------------------------------------------------------------------
// the threads

/// The record of a thread, at the top of its mapping (below its
/// thread-local storage): what it runs, its stack, its mapping, and the
/// word the kernel sets to 0, and wakes, when it has ended
/// (`CLONE_CHILD_CLEARTID`).
#[repr(C)]
struct Record {
    f: Entry,
    arg: *mut c_void,
    stack_low: usize,
    stack_size: usize,
    base: usize,
    len: usize,
    tid: AtomicU32,
}

const CLONE_VM: usize = 0x100;
const CLONE_FS: usize = 0x200;
const CLONE_FILES: usize = 0x400;
const CLONE_SIGHAND: usize = 0x800;
const CLONE_THREAD: usize = 0x10000;
const CLONE_SYSVSEM: usize = 0x40000;
const CLONE_SETTLS: usize = 0x80000;
const CLONE_PARENT_SETTID: usize = 0x100000;
const CLONE_CHILD_CLEARTID: usize = 0x200000;

/// A thread running `f(arg)` on a stack of `stack` bytes (reserved, not
/// committed: only the pages touched are memory), a page below it that
/// faults; its record (0 if it could not be made).
fn spawn(stack: usize, f: Entry, arg: *mut c_void) -> usize {
    let stack = (stack.max(64 << 10) + PAGE - 1) & !(PAGE - 1);
    let area = tls_area();
    let len = PAGE + stack + area;
    let Some(m) = new_mapping(len, 0x4000 | 0x20000) else {
        return 0;
    };
    let base = m.as_ptr() as usize;
    // SAFETY: the lowest page of the new mapping made a guard
    unsafe { mprotect(base as *mut c_void, PAGE, 0) };
    let tp = place_tls(&mut m[len - area..]);
    let rec = ((tp - tls().below_tp() - core::mem::size_of::<Record>()) & !63) as *mut Record;
    // SAFETY: the record, aligned, below the thread-local storage and above
    // the stack, inside the mapping (`tls_area` keeps room for it)
    unsafe { rec.write(Record { f, arg, stack_low: base + PAGE, stack_size: rec as usize - (base + PAGE), base, len, tid: AtomicU32::new(0) }) };
    let sp = (rec as usize) & !15;
    let flags = CLONE_VM | CLONE_FS | CLONE_FILES | CLONE_SIGHAND | CLONE_THREAD | CLONE_SYSVSEM | CLONE_SETTLS | CLONE_PARENT_SETTID | CLONE_CHILD_CLEARTID;
    // SAFETY: the word of the record, inside the mapping
    let tid = unsafe { core::ptr::addr_of!((*rec).tid) } as usize;
    let r: isize;
    // SAFETY: `clone` of a thread of this process with its own stack (`sp`,
    // in its mapping) and thread-local storage (`tp`); the new thread starts
    // after `syscall` with `rax` 0 and the stack `sp`, on which the record
    // was put first: it calls `thread_main` with it, then ends (`exit`, this
    // thread only); it never leaves this block, which the calling thread
    // leaves with the result of `clone`
    unsafe {
        asm!(
            "mov [{sp} - 8], {rec}",
            "sub {sp}, 16",
            "mov rsi, {sp}",
            "syscall",
            "test rax, rax",
            "jnz 2f",
            "xor ebp, ebp",
            "mov rdi, [rsp + 8]",
            "call {main}",
            "xor edi, edi",
            "mov eax, 60",
            "syscall",
            "ud2",
            "2:",
            sp = inout(reg) sp => _,
            rec = in(reg) rec,
            main = sym thread_main,
            inlateout("rax") 56isize => r,
            in("rdi") flags,
            out("rsi") _,
            in("rdx") tid,
            in("r10") tid,
            in("r8") tp,
            lateout("rcx") _,
            lateout("r11") _,
        );
    }
    if r < 0 {
        // SAFETY: the mapping of no thread
        unsafe { munmap(base as *mut c_void, len) };
        return 0;
    }
    rec as usize
}

/// The start of a thread of `spawn`: the bounds of its stack, its function,
/// then its cache of the heap given back.
extern "C" fn thread_main(rec: *mut Record) {
    // SAFETY: the record `spawn` wrote, alive until the thread is joined
    let r = unsafe { &*rec };
    set_stack(r.stack_low, r.stack_size);
    (r.f)(r.arg);
    super::heap::thread_exit();
}

/// The end of a thread of `spawn` waited for (the kernel sets its word to
/// 0 and wakes it when the thread has ended: not a private futex), then
/// its mapping given back.
fn join(h: usize) {
    let rec = h as *const Record;
    // SAFETY: the record of a thread of `spawn` not joined yet
    let (tid, base, len) = unsafe { (&(*rec).tid, (*rec).base, (*rec).len) };
    loop {
        let v = tid.load(Ordering::Acquire);
        if v == 0 {
            break;
        }
        futex(tid, 0, v);
    }
    // SAFETY: the thread has ended: nothing uses its mapping
    unsafe { munmap(base as *mut c_void, len) };
}

