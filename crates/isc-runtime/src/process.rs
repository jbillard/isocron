//! The process of a program under Linux on x86-64 without a C library
//! (D289): its start (`isc_start`, the entry of the static programs), its
//! thread-local storage, its threads (`clone`) and the bounds of their
//! stacks. A program that declares C functions keeps glibc (its `_start`,
//! its threads, its allocator for `ISC_ALLOC=glibc`): `isc_os` is the one
//! table of functions or the other, chosen when the program is linked
//! (`--defsym=isc_os=isc_os_own` or `isc_os_glibc`); the code of the other
//! one is dropped by the linker with the C functions it calls.
//!
//! The static programs are position-independent (`-static -pie`): their
//! addresses are random, as before, so `isc_start` applies their
//! relocations itself (as the dynamic loader did), in assembly, before any
//! code that reads an address from memory; then their constant data is
//! made read-only (`PT_GNU_RELRO`, as the loader does).

use super::linux::{exit, futex, mmap, mprotect, munmap, syscall6, MAP_FAILED};
use core::arch::{asm, global_asm};
use core::ffi::{c_int, c_void};
use core::sync::atomic::{AtomicU32, AtomicUsize, Ordering};

/// The function a thread runs.
pub type Entry = extern "C" fn(*mut c_void) -> *mut c_void;

/// The functions of the threads and of the allocator of glibc: the
/// runtime's (`isc_os_own`) or glibc's (`isc_os_glibc`).
pub struct Os {
    /// A thread running `f(arg)` on a stack of `stack` bytes (or of the
    /// default size if that cannot be had): a handle for `join`, 0 if none.
    pub spawn: fn(usize, Entry, *mut c_void) -> usize,
    /// The end of a thread of `spawn` waited for.
    pub join: fn(usize),
    /// The lowest address of the stack of the calling thread and its size
    /// (0 and 0 when not known).
    pub stack: fn() -> (usize, usize),
    /// The cache of the calling thread for the heap, given back when the
    /// thread ends: by glibc (a key of pthread), or by the thread itself
    /// (`thread_main`), which then needs nothing here.
    pub register: unsafe fn(*mut c_void),
    /// The allocator of glibc (`ISC_ALLOC=glibc`), if any.
    pub alloc: Option<unsafe extern "C" fn(usize, usize) -> *mut c_void>,
    pub free: Option<unsafe extern "C" fn(*mut c_void)>,
}

extern "Rust" {
    /// `isc_os_own` or `isc_os_glibc` (`--defsym` of the link).
    static isc_os: Os;
}

/// The functions of this program.
#[inline(always)]
pub fn os() -> &'static Os {
    // SAFETY: `isc_os` is one of the two tables below, constant (the link
    // defines it, `iscc` always does)
    unsafe { &isc_os }
}

#[no_mangle]
pub static isc_os_own: Os = Os { spawn, join, stack: own_stack, register: register_nothing, alloc: None, free: None };

#[no_mangle]
pub static isc_os_glibc: Os = Os {
    spawn: glibc::spawn,
    join: glibc::join,
    stack: glibc::stack,
    register: super::heap::register_with_key,
    alloc: Some(glibc::aligned_alloc),
    free: Some(glibc::free),
};

/// Nothing: the threads of the runtime give their cache back themselves.
unsafe fn register_nothing(_: *mut c_void) {}

