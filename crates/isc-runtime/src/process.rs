// The entry of a static program: the stack the kernel made at `rsp`
// (argc, the arguments, 0, the environment, 0, the auxiliary vector). The
// relocations of the program (`R_X86_64_RELATIVE`, the only kind of a
// static PIE) applied to its load address (that of its ELF header,
// `__ehdr_start`), from the table `DT_RELA` of `_DYNAMIC`, then `start`.
global_asm!(
    ".section .text.isc_start,\"ax\",@progbits",
    ".globl isc_start",
    ".type isc_start,@function",
    "isc_start:",
    "xor ebp, ebp",
    "mov r12, rsp",
    "lea rdi, [rip + __ehdr_start]",
    "lea rsi, [rip + _DYNAMIC]",
    "xor ecx, ecx",
    "xor edx, edx",
    // DT_RELA (7) and DT_RELASZ (8) in the dynamic section (ended by 0)
    "2:",
    "mov rax, [rsi]",
    "test rax, rax",
    "jz 4f",
    "cmp rax, 7",
    "jne 3f",
    "mov rcx, [rsi + 8]",
    "3:",
    "cmp rax, 8",
    "jne 5f",
    "mov rdx, [rsi + 8]",
    "5:",
    "add rsi, 16",
    "jmp 2b",
    // each entry of 24 bytes: offset, info (its type in the low 32 bits),
    // addend; R_X86_64_RELATIVE (8): base + addend written at base + offset
    "4:",
    "test rcx, rcx",
    "jz 9f",
    "add rcx, rdi",
    "add rdx, rcx",
    "6:",
    "cmp rcx, rdx",
    "jae 9f",
    "cmp dword ptr [rcx + 8], 8",
    "jne 7f",
    "mov rax, [rcx + 16]",
    "add rax, rdi",
    "mov r8, [rcx]",
    "mov [rdi + r8], rax",
    "7:",
    "add rcx, 24",
    "jmp 6b",
    "9:",
    "mov rdi, r12",
    "and rsp, -16",
    "call {start}",
    "ud2",
    ".size isc_start, . - isc_start",
    ".text",
    start = sym start,
);

extern "C" {
    /// The `main` of the program (generated by `iscc`).
    fn main(argc: c_int, argv: *const *const u8) -> c_int;
}

/// The address of the ELF header of the program (its load address).
fn ehdr() -> *const u8 {
    let p: *const u8;
    // SAFETY: an address computed relative to the instruction, nothing read
    unsafe { asm!("lea {}, [rip + __ehdr_start]", out(reg) p, options(nomem, nostack, pure, preserves_flags)) };
    p
}

/// The image of the thread-local storage of the program (`PT_TLS`): its
/// address, the bytes given (`.tdata`), its size, its alignment, its
/// address in the file (for the offsets of the linker).
#[derive(Clone, Copy)]
struct Tls {
    image: usize,
    filesz: usize,
    memsz: usize,
    align: usize,
    vaddr: usize,
}

/// `Tls`, read once by `start` before any thread.
static TLS_IMAGE: AtomicUsize = AtomicUsize::new(0);
static TLS_FILESZ: AtomicUsize = AtomicUsize::new(0);
static TLS_MEMSZ: AtomicUsize = AtomicUsize::new(0);
static TLS_ALIGN: AtomicUsize = AtomicUsize::new(1);
static TLS_VADDR: AtomicUsize = AtomicUsize::new(0);

fn tls() -> Tls {
    Tls {
        image: TLS_IMAGE.load(Ordering::Relaxed),
        filesz: TLS_FILESZ.load(Ordering::Relaxed),
        memsz: TLS_MEMSZ.load(Ordering::Relaxed),
        align: TLS_ALIGN.load(Ordering::Relaxed),
        vaddr: TLS_VADDR.load(Ordering::Relaxed),
    }
}

impl Tls {
    /// The bytes from the start of the block to the thread pointer, as the
    /// linker counts them for x86-64 (`tpoff`): the size, then up to where
    /// `vaddr + size` is aligned.
    fn below_tp(&self) -> usize {
        self.memsz + (0usize.wrapping_sub(self.vaddr).wrapping_sub(self.memsz) & (self.align - 1))
    }
}

/// The bytes of the control block of a thread above its thread pointer:
/// its first word points to itself (`%fs:0`, the only one the code reads).
const TCB: usize = 64;
const PAGE: usize = 4096;

/// The word of `N` bytes (little-endian) at `at` in `b`, 0 past its end.
fn word<const N: usize>(b: &[u8], at: usize) -> usize {
    let mut v = [0u8; 8];
    if let Some(s) = b.get(at..at + N) {
        v[..N].copy_from_slice(s);
    }
    usize::from_le_bytes(v)
}

/// The program headers: `PT_TLS` noted, `PT_GNU_RELRO` made read-only.
///
/// # Safety
/// Once, by `start`, after the relocations.
unsafe fn read_headers() {
    let base = ehdr();
    // SAFETY: the ELF header (64 bytes) and the program headers are in the
    // first segment of the program, mapped at `base` (`__ehdr_start`) for its
    // whole life, never written
    let header = unsafe { core::slice::from_raw_parts(base, 64) };
    let (phoff, phentsize, phnum) = (word::<8>(header, 0x20), word::<2>(header, 0x36), word::<2>(header, 0x38));
    // SAFETY: as above
    let headers = unsafe { core::slice::from_raw_parts(base.add(phoff), phnum * phentsize) };
    for h in headers.chunks_exact(phentsize.max(1)) {
        let (vaddr, filesz, memsz, align) = (word::<8>(h, 16), word::<8>(h, 32), word::<8>(h, 40), word::<8>(h, 48));
        match word::<4>(h, 0) {
            7 => {
                TLS_IMAGE.store(base as usize + vaddr, Ordering::Relaxed);
                TLS_FILESZ.store(filesz, Ordering::Relaxed);
                TLS_MEMSZ.store(memsz, Ordering::Relaxed);
                TLS_ALIGN.store(align.max(1), Ordering::Relaxed);
                TLS_VADDR.store(vaddr, Ordering::Relaxed);
            }
            0x6474_e552 => {
                let lo = (base as usize + vaddr) & !(PAGE - 1);
                let hi = (base as usize + vaddr + memsz) & !(PAGE - 1);
                if hi > lo {
                    // SAFETY: the constant data of the program, written only by
                    // the relocations, done
                    unsafe { mprotect(lo as *mut c_void, hi - lo, 1) };
                }
            }
            _ => {}
        }
    }
}

/// The image of the thread-local storage (`.tdata`).
fn tls_image() -> &'static [u8] {
    let t = tls();
    if t.filesz == 0 {
        return &[];
    }
    // SAFETY: the `filesz` bytes of `PT_TLS` of the program, mapped for its
    // whole life (read by `read_headers` before any thread)
    unsafe { core::slice::from_raw_parts(t.image as *const u8, t.filesz) }
}

/// The thread-local storage of a thread placed at the top of `region`
/// (zeros): the control block at the thread pointer, the block below it,
/// the image copied; the thread pointer (0 if it does not fit).
fn place_tls(region: &mut [u8]) -> usize {
    let t = tls();
    let align = t.align.max(64);
    let lo = region.as_ptr() as usize;
    let hi = lo + region.len();
    if hi < lo + TCB + t.below_tp() + align {
        return 0;
    }
    let tp = (hi - TCB) & !(align - 1);
    let (tp_at, block_at) = (tp - lo, tp - t.below_tp() - lo);
    let image = tls_image();
    region[block_at..block_at + image.len()].copy_from_slice(image);
    // the first word of the control block: the thread pointer itself
    region[tp_at..tp_at + 8].copy_from_slice(&tp.to_ne_bytes());
    tp
}

/// The bytes a thread needs above its stack: its thread-local storage, its
/// control block, the record of the thread.
fn tls_area() -> usize {
    let t = tls();
    (t.below_tp() + TCB + t.align.max(64) + core::mem::size_of::<Record>() + 64 + PAGE - 1) & !(PAGE - 1)
}

/// The thread-local storage of the main thread, when it fits (no system
/// call): otherwise mapped.
#[repr(C, align(64))]
struct MainTls([u8; 4096]);
static mut MAIN_TLS: MainTls = MainTls([0; 4096]);

/// The thread pointer of the calling thread set to `tp`.
fn set_thread_pointer(tp: usize) {
    const ARCH_SET_FS: usize = 0x1002;
    // SAFETY: `arch_prctl` sets the base of `fs` and reads no memory
    unsafe { syscall6(158, ARCH_SET_FS, tp, 0, 0, 0, 0) };
}

/// A new private mapping of `len` bytes (zeros), its flags `flags` with
/// `MAP_PRIVATE | MAP_ANONYMOUS`; none if the system has no memory.
fn new_mapping(len: usize, flags: c_int) -> Option<&'static mut [u8]> {
    // SAFETY: a new mapping, of no other memory
    let m = unsafe { mmap(core::ptr::null_mut(), len, 3, 0x22 | flags, -1, 0) };
    if m == MAP_FAILED {
        return None;
    }
    // SAFETY: the `len` bytes just mapped, given to the caller alone
    Some(unsafe { core::slice::from_raw_parts_mut(m as *mut u8, len) })
}

/// The start of the program, from `isc_start`: the headers read, the
/// thread-local storage of the main thread, the bounds of its stack, then
/// `main`, then the end of the process with its code.
///
/// # Safety
/// From `isc_start` only, with the stack the kernel made.
unsafe extern "C" fn start(sp: *const usize) -> ! {
    // SAFETY: once, before anything else (see above)
    unsafe { read_headers() };
    // the stack of the kernel: argc, argv[argc], 0, envp..., 0, then the
    // auxiliary vector (pairs, ended by a pair of type 0)
    // SAFETY: each word read is in that stack, before its last 0
    let at = |k: usize| unsafe { *sp.add(k) };
    let argc = at(0);
    let mut k = argc + 2;
    while at(k) != 0 {
        k += 1;
    }
    k += 1;
    let mut execfn = 0usize;
    while at(k) != 0 {
        if at(k) == 31 {
            execfn = at(k + 1);
        }
        k += 2;
    }
    // SAFETY: the buffer of the main thread, used by nothing else (no other
    // thread yet)
    let main_tls = unsafe { &mut (*core::ptr::addr_of_mut!(MAIN_TLS)).0 };
    let mut tp = place_tls(main_tls);
    if tp == 0 {
        match new_mapping(tls_area(), 0) {
            Some(m) => tp = place_tls(m),
            None => exit(127),
        }
    }
    set_thread_pointer(tp);
    // the stack of the main thread: from above the name of the program
    // (`AT_EXECFN`, the last thing the kernel put at its top) down by its
    // limit (`RLIMIT_STACK`, at most 8 MiB counted)
    if execfn != 0 {
        // SAFETY: `AT_EXECFN` is a string ending with a zero byte
        let name = unsafe { super::strlen(execfn as *const core::ffi::c_char) };
        let top = (execfn + name + 1 + 8 + PAGE - 1) & !(PAGE - 1);
        let mut limit = [0u64; 2];
        // SAFETY: `prlimit64` writes one `rlimit` (16 bytes) into `limit`
        unsafe { syscall6(302, 0, 3, 0, limit.as_mut_ptr() as usize, 0, 0) };
        let size = (limit[0] as usize).min(8 << 20);
        set_stack(top - size, size);
    }
    // SAFETY: the `main` of the program with the arguments of the kernel
    exit(unsafe { main(argc as c_int, sp.add(1) as *const *const u8) })
}

