// glibc's, for the programs that declare C functions (D125)

mod glibc {
    use super::Entry;
    use core::ffi::{c_int, c_void};

    extern "C" {
        fn pthread_create(tid: *mut usize, attr: *const c_void, f: Entry, arg: *mut c_void) -> c_int;
        fn pthread_join(t: usize, ret: *mut *mut c_void) -> c_int;
        fn pthread_attr_init(attr: *mut c_void) -> c_int;
        fn pthread_attr_setstacksize(attr: *mut c_void, size: usize) -> c_int;
        fn pthread_attr_destroy(attr: *mut c_void) -> c_int;
        fn pthread_self() -> usize;
        fn pthread_getattr_np(t: usize, attr: *mut c_void) -> c_int;
        fn pthread_attr_getstack(attr: *const c_void, addr: *mut *mut c_void, size: *mut usize) -> c_int;
        pub fn aligned_alloc(align: usize, size: usize) -> *mut c_void;
        pub fn free(p: *mut c_void);
    }

    pub fn spawn(stack: usize, f: Entry, arg: *mut c_void) -> usize {
        // pthread_attr_t: 56 bytes with glibc on x86-64
        let mut attr = [0u64; 16];
        let a = attr.as_mut_ptr() as *mut c_void;
        let mut tid = 0usize;
        // SAFETY: the functions of pthread on an attribute of the size glibc
        // needs, initialised and destroyed here
        unsafe {
            let big = pthread_attr_init(a) == 0 && pthread_attr_setstacksize(a, stack) == 0 && pthread_create(&mut tid, a, f, arg) == 0;
            pthread_attr_destroy(a);
            if !big && pthread_create(&mut tid, core::ptr::null(), f, arg) != 0 {
                return 0;
            }
        }
        tid
    }

    pub fn join(t: usize) {
        // SAFETY: a thread of `spawn`, joined once
        unsafe { pthread_join(t, core::ptr::null_mut()) };
    }

    pub fn stack() -> (usize, usize) {
        let mut attr = [0u64; 16];
        let a = attr.as_mut_ptr() as *mut c_void;
        let mut addr: *mut c_void = core::ptr::null_mut();
        let mut size = 0usize;
        // SAFETY: as `spawn`
        unsafe {
            if pthread_getattr_np(pthread_self(), a) != 0 {
                return (0, 0);
            }
            let ok = pthread_attr_getstack(a, &mut addr, &mut size) == 0;
            pthread_attr_destroy(a);
            if !ok {
                return (0, 0);
            }
        }
        (addr as usize, size)
    }
}
