#!/usr/bin/env python3
"""The table of `f64_text.h` (D415): for each k from K_MIN to K_MAX, the
126 bits of 10^-k (Schubfach, R. Giulietti): with 10^-k = beta 2^r and
2^125 <= beta < 2^126, g = floor(beta) + 1, written as its high 63 bits and
its low 63 bits. Computed exactly with integers.
    gen_pow10.py > pow10_table.h"""
from fractions import Fraction

K_MIN, K_MAX = -324, 292


def flog2pow10(e):
    return (e * 913124641741) >> 38


def main():
    print("// Generated by gen_pow10.py (D415): do not edit.")
    print("static const unsigned long long POW10_G[%d][2] = {" % (K_MAX - K_MIN + 1))
    for k in range(K_MIN, K_MAX + 1):
        v = Fraction(10) ** (-k)
        # the exact floor of log2(10^-k), checked against the formula of the C code
        e = -k
        exact = (10 ** e).bit_length() - 1 if e >= 0 else -((10 ** -e).bit_length())
        assert exact == flog2pow10(e), (k, exact, flog2pow10(e))
        r = exact - 125
        beta = v / (Fraction(2) ** r)
        assert 2 ** 125 <= beta < 2 ** 126, k
        g = beta.numerator // beta.denominator + 1
        print("    {0x%016xULL, 0x%016xULL}," % (g >> 63, g & ((1 << 63) - 1)))
    print("};")


main()
