#!/usr/bin/env python3
"""results/benchmarks_game.md from the lines of measure.sh, and the
summary of the results in README.md (between its markers).

    report.py results/benchmarks_game.tsv COMMIT DECISION DATE > results/benchmarks_game.md

The floors: results/floors.tsv (written by bench/floor/floors.py). The look
on GitHub: bench/mdstyle.py (D235).

For each benchmark: the time of each language (the fastest program of that
language on the site of the Benchmarks Game), Isocron's, its ratio to the
fastest, and its ratio to the fastest of the measured programs that use
neither x86 intrinsics nor a library of their own (GMP, PCRE): those found by
looking for them in the sources of bench/benchmarks_game/upstream.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LANGS = [("C", "gcc"), ("C++", "gpp"), ("Rust", "rust"), ("Go", "go")]
SIMD = re.compile(r"immintrin|emmintrin|xmmintrin|_mm_|_mm256|_mm512|__m128|__m256|std::arch|core::arch|vector_size|__builtin_ia32")
GMP = re.compile(r"gmp\.h|mpz_|rug::")
PCRE = re.compile(r"pcre|PCRE")


def source(bench, prog):
    ext = re.sub(r"-\d+$", "", prog)
    name = "%s.%s" % (bench, ext) if prog == ext else "%s.%s.%s" % (bench, prog, ext)
    return os.path.join(HERE, "upstream", bench, name)


def uses(bench, prog):
    """What the program uses beyond its language: lines of intrinsics, of GMP, of PCRE."""
    try:
        text = open(source(bench, prog), errors="replace").read().splitlines()
    except OSError:
        return None
    found = []
    for label, pat in (("SIMD", SIMD), ("GMP", GMP), ("PCRE", PCRE)):
        n = sum(1 for l in text if pat.search(l))
        if n:
            found.append("%s (%d lines)" % (label, n))
    return found


def ms(x):
    return "%d" % x


def floors():
    """The floor of each program (results/floors.tsv, written by floors.py)."""
    out = {}
    try:
        for line in open(os.path.join(HERE, "..", "..", "results", "floors.tsv")):
            p = line.split()
            if len(p) == 2:
                out[p[0]] = float(p[1])
    except OSError:
        pass
    return out


def main():
    sys.path.insert(0, os.path.join(HERE, ".."))
    import mdstyle as md

    tsv, commit, decision, date = sys.argv[1:5]
    times = {}
    for line in open(tsv):
        mode, bench, prog, t = line.split()
        if mode != "native" or not t.isdigit():
            continue
        times.setdefault(bench, {})[prog] = int(t)
    fl = floors()
    rows = []
    notes = []
    for bench in sorted(times):
        row = times[bench]
        iso = row.get("isocron")
        cells, best, plain = [], None, None
        for lang, prefix in LANGS:
            progs = [(p, t) for p, t in row.items() if re.sub(r"-\d+$", "", p) == prefix]
            if not progs:
                cells.append(None)
                continue
            p, t = min(progs, key=lambda x: x[1])
            cells.append(t)
            if best is None or t < best[2]:
                best = (lang, p, t)
            u = uses(bench, p)
            if u == []:
                if plain is None or t < plain[2]:
                    plain = (lang, p, t)
            elif u:
                notes.append((bench, lang, p, u))
        rows.append((bench, iso, cells, best, plain))
    ahead = sum(1 for b, iso, c, best, pl in rows if iso and best and iso < best[2])
    out = []
    out.append("# The ten programs of the Benchmarks Game\n")
    out.append("> [!NOTE]\n> **Intermediate results**: Isocron at commit `%s` (DECISIONS %s), %s. The work on the ten "
               "programs goes on, and these numbers will change. Generated by `bench/benchmarks_game/report.py` from "
               "`%s` (the raw lines of `bench/benchmarks_game/measure.sh`).\n"
               % (commit, decision, date, os.path.relpath(tsv, os.path.join(HERE, "..", ".."))))
    out.append("**Isocron is the fastest on %d of the %d programs.** Elapsed time in milliseconds, the lowest of 3 runs, "
               "at the sizes of the Benchmarks Game, 4 threads, in Docker on an Intel Xeon E-2388G ([protocol](#protocol)). "
               "The *floor* is what the result requires at the cost of the cheapest way the machine has to do it, never "
               "the time of a program ([floors.md](floors.md)). Isocron's programs use no intrinsics and no library of "
               "their own: the compiler makes their vector code and their parallel code.\n" % (ahead, len(rows)))
    out.append("| | benchmark | floor | C | C++ | Rust | Go | Isocron | Isocron / fastest | Isocron / floor |")
    out.append("| :-: | :-- | --: | --: | --: | --: | --: | --: | :-: | :-: |")
    chart = []
    for bench, iso, cells, best, plain in rows:
        cs = []
        for i, (lang, _) in enumerate(LANGS):
            t = cells[i]
            if t is None:
                cs.append("–")
            elif best and lang == best[0] and not (iso and iso < best[2]):
                cs.append("**%s**" % ms(t))
            else:
                cs.append(ms(t))
        r = iso / best[2] if iso and best else None
        f = fl.get(bench)
        isos = ("**%s**" % ms(iso) if r is not None and r < 1 else ms(iso)) if iso else "–"
        out.append("| %s | **%s** | %s | %s | %s | %s | %s |" % (
            md.status(r) if r is not None else "", md.name(bench), "%.1f" % (f * 1000) if f else "–", " | ".join(cs), isos,
            md.vs_fastest(r) if r is not None else "–", md.vs_floor(iso / 1000 / f) if f and iso else "–"))
        if r is not None:
            chart.append((md.name(bench), r))
    out.append("")
    out.append(md.LEGEND + " The fastest of the four other languages in **bold**, or Isocron when it is faster.\n")
    out.append(md.bar_chart("Isocron time / fastest of C, C++, Rust, Go (below 1: faster)",
                            [c[0] for c in chart], [c[1] for c in chart], "ratio", "%.1f" % (max(c[1] for c in chart) * 1.1 + 0.1), [1.0] * len(chart)))
    out.append("")
    out.append("<details>\n<summary><b>Against the programs without intrinsics nor libraries</b>: the fastest of the four "
               "measured programs that use neither x86 intrinsics nor a library of their own (GMP, PCRE)</summary>\n")
    out.append("| benchmark | fastest plain | Isocron / plain |")
    out.append("| :-- | :-- | :-: |")
    for bench, iso, cells, best, plain in rows:
        if plain and iso:
            out.append("| %s | %s %s | %s |" % (md.name(bench), plain[0], ms(plain[2]), md.vs_fastest(iso / plain[2])))
        else:
            out.append("| %s | – | – |" % md.name(bench))
    out.append("\n</details>\n")
    out.append("<details>\n<summary><b>What the measured programs use beyond their language</b> (lines of their source that "
               "name x86 intrinsics, GMP or PCRE; a search of words, not a reading of the programs)</summary>\n")
    out.append("| benchmark | language | program | uses |")
    out.append("| :-- | :-- | :-- | :-- |")
    for bench, lang, p, u in notes:
        out.append("| %s | %s | %s | %s |" % (md.name(bench), lang, p, ", ".join(u)))
    out.append("\n</details>\n")
    out.append("## Notes\n")
    out.append("* fannkuch-redux: the Isocron program was rewritten twice (D170: by chunks of permutations, without "
               "divisions; D197: the flips of a chunk as a `map`, in vector code). Part of its gain comes from the "
               "program, not from the language; the nine others are their first version (D160), but for names of the "
               "standard library.")
    gaps = []
    for bench, iso, cells, best, plain in rows:
        f = fl.get(bench)
        if f and iso:
            gaps.append(iso / 1000 / f)
        if f and best:
            gaps.append(best[2] / 1000 / f)
    span = " by %.1f to %.0f times" % (min(gaps), max(gaps)) if gaps else ""
    out.append("* The floors: `results/floors.md` (D222, D227, D233). Every program here, of every language, is still "
               "above its floor%s." % span)
    out.append("")
    # the programs and the protocol of the measurements (a file of their own)
    out.append(open(os.path.join(HERE, "protocol.md")).read().rstrip("\n"))
    sys.stdout.write("\n".join(out) + "\n")
    readme(rows, fl, commit, decision, ahead, md)


def readme(rows, fl, commit, decision, ahead, md):
    """The summary of the results in README.md, between its two markers."""
    path = os.path.join(HERE, "..", "..", "README.md")
    try:
        text = open(path).read()
    except OSError:
        return
    begin, end = "<!-- results:begin -->", "<!-- results:end -->"
    if begin not in text or end not in text:
        return
    lines = [begin, "",
             "**Isocron is the fastest on %d of the %d programs of the Benchmarks Game** (commit `%s`, DECISIONS %s; "
             "4 threads, Intel Xeon E-2388G; [details](results/benchmarks_game.md), [floors](results/floors.md))." % (ahead, len(rows), commit, decision),
             "",
             "| | benchmark | Isocron | fastest other | Isocron / fastest | floor | Isocron / floor |",
             "| :-: | :-- | --: | :-- | :-: | --: | :-: |"]
    for bench, iso, cells, best, plain in rows:
        if not (iso and best):
            continue
        r = iso / best[2]
        f = fl.get(bench)
        lines.append("| %s | %s | %s ms | %s %s ms | %s | %s | %s |" % (
            md.status(r), md.name(bench), ms(iso), best[0], ms(best[2]), md.vs_fastest(r),
            "%.1f ms" % (f * 1000) if f else "–", md.vs_floor(iso / 1000 / f) if f else "–"))
    lines += ["", md.LEGEND, ""]
    # the same ratios drawn, an image written beside (docs/media/benchmarks.svg)
    shown = [(md.name(bench), iso / best[2]) for bench, iso, cells, best, plain in rows if iso and best]
    if shown:
        media = os.path.join(HERE, "..", "..", "docs", "media")
        os.makedirs(media, exist_ok=True)
        with open(os.path.join(media, "benchmarks.svg"), "w") as h:
            h.write(md.ratio_svg("Time of Isocron / time of the fastest other program",
                                 "Lower is faster: 0.5 is twice as fast. Commit %s, 4 threads, Intel Xeon E-2388G." % commit,
                                 shown, "the fastest of C, C++, Rust, Go"))
        lines += ['<p align="center"><img src="docs/media/benchmarks.svg" width="720" '
                  'alt="Time of Isocron over the time of the fastest other program, for each of the ten programs"></p>', ""]
    lines += [end]
    a = text.index(begin)
    b = text.index(end) + len(end)
    open(path, "w").write(text[:a] + "\n".join(lines) + text[b:])


if __name__ == "__main__":
    main()
