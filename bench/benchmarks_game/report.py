#!/usr/bin/env python3
"""results/benchmarks_game.md from the lines of measure.sh.

    report.py results/benchmarks_game.tsv COMMIT DECISION DATE > results/benchmarks_game.md

For each benchmark: the time of each language (the fastest program of that
language on the site of the Benchmarks Game), Isocron's, its ratio to the
fastest, and its ratio to the fastest of the measured programs that use
neither x86 intrinsics nor a library of their own (GMP, PCRE): those found by
looking for them in the sources of bench/benchmarks_game/upstream.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LANGS = [("C", "gcc"), ("C++", "gpp"), ("Rust", "rust"), ("Go", "go")]
SIMD = re.compile(r"immintrin|emmintrin|xmmintrin|_mm_|_mm256|_mm512|__m128|__m256|std::arch|core::arch|vector_size|__builtin_ia32")
GMP = re.compile(r"gmp\.h|mpz_|rug::")
PCRE = re.compile(r"pcre|PCRE")


def source(bench, prog):
    ext = re.sub(r"-\d+$", "", prog)
    name = "%s.%s" % (bench, ext) if prog == ext else "%s.%s.%s" % (bench, prog, ext)
    return os.path.join(HERE, "upstream", bench, name)


def uses(bench, prog):
    """What the program uses beyond its language: lines of intrinsics, of GMP, of PCRE."""
    try:
        text = open(source(bench, prog), errors="replace").read().splitlines()
    except OSError:
        return None
    found = []
    for label, pat in (("SIMD", SIMD), ("GMP", GMP), ("PCRE", PCRE)):
        n = sum(1 for l in text if pat.search(l))
        if n:
            found.append("%s (%d lines)" % (label, n))
    return found


def ms(x):
    return "%d" % x


def main():
    tsv, commit, decision, date = sys.argv[1:5]
    times = {}
    for line in open(tsv):
        mode, bench, prog, t = line.split()
        if mode != "native" or not t.isdigit():
            continue
        times.setdefault(bench, {})[prog] = int(t)
    out = []
    out.append("# The ten programs of the Benchmarks Game, measured\n")
    out.append(
        "**Intermediate results**: Isocron at commit %s (DECISIONS %s), %s; the work on the ten programs goes on, "
        "and these numbers will change. Generated by `bench/benchmarks_game/report.py` from `%s` (the raw lines of "
        "`bench/benchmarks_game/measure.sh`).\n" % (commit, decision, date, os.path.relpath(tsv, os.path.join(HERE, "..", "..")))
    )
    out.append(
        "Elapsed time in milliseconds, the lowest of 3 runs, at the sizes of the Benchmarks Game. *Isocron / fastest*: "
        "the time of Isocron over the time of the fastest of the four other languages (below 1: Isocron is faster). "
        "*Fastest plain*: the fastest of the four measured programs that use neither x86 intrinsics nor a library of "
        "their own (GMP, PCRE), and Isocron over it. Isocron's programs use neither: the compiler makes their vector "
        "code and their parallel code.\n"
    )
    out.append("| benchmark | C | C++ | Rust | Go | Isocron | Isocron / fastest | fastest plain | Isocron / plain |")
    out.append("| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | ---: |")
    notes = []
    for bench in sorted(times):
        row = times[bench]
        iso = row.get("isocron")
        cells = []
        best = None
        plain = None
        for lang, prefix in LANGS:
            progs = [(p, t) for p, t in row.items() if re.sub(r"-\d+$", "", p) == prefix]
            if not progs:
                cells.append("–")
                continue
            p, t = min(progs, key=lambda x: x[1])
            cells.append(ms(t))
            if best is None or t < best[2]:
                best = (lang, p, t)
            u = uses(bench, p)
            if u == []:
                if plain is None or t < plain[2]:
                    plain = (lang, p, t)
            elif u:
                notes.append((bench, lang, p, u))
        for i, (lang, _) in enumerate(LANGS):
            if best and lang == best[0] and cells[i] != "–":
                cells[i] = "**%s**" % cells[i]
        ratio = "%.2f" % (iso / best[2]) if iso and best else "–"
        if plain:
            pl = "%s %s" % (plain[0], ms(plain[2]))
            pr = "%.2f" % (iso / plain[2]) if iso else "–"
        else:
            pl, pr = "–", "–"
        out.append("| %s | %s | %s | %s | %s | %s |" % (bench, " | ".join(cells), ms(iso) if iso else "–", ratio, pl, pr))
    out.append("")
    out.append("What the measured programs use beyond their language (lines of their source that name x86 intrinsics, "
               "GMP or PCRE; a search of words, not a reading of the programs):\n")
    out.append("| benchmark | language | program | uses |")
    out.append("| --- | --- | --- | --- |")
    for bench, lang, p, u in notes:
        out.append("| %s | %s | %s | %s |" % (bench, lang, p, ", ".join(u)))
    out.append("")
    out.append("Notes:\n")
    out.append("* fannkuch-redux: the Isocron program was rewritten twice (D170: by chunks of permutations, without "
               "divisions; D197: the flips of a chunk as a `map`, in vector code). Part of its gain comes from the "
               "program, not from the language; the nine others are their first version (D160), but for names of the "
               "standard library.")
    # the gaps to the floors, from the table of results/floors.md
    gaps = []
    try:
        for line in open(os.path.join(HERE, "..", "..", "results", "floors.md")):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) == 8 and cells[0] in times:
                gaps.append(float(cells[5]))
                gaps.append(float(cells[7]))
    except (OSError, ValueError):
        gaps = []
    span = " by %.1f to %.0f times" % (min(gaps), max(gaps)) if gaps else ""
    out.append("* The floor of each program on this machine, what its result requires at the cost of the cheapest way "
               "the machine has to do it, never the time of a program (D222): `results/floors.md`. Every program here, "
               "of every language, is still above its floor%s." % span)
    out.append("")
    # the programs and the protocol of the measurements (a file of their own)
    out.append(open(os.path.join(HERE, "protocol.md")).read().rstrip("\n"))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
