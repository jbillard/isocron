#!/usr/bin/env python3
"""Study of V, the number of interleaved accumulators of the fixed reduction
form (SPEC section 10; DECISIONS D55, D56), point 2 of the improvements after
the POC.

Measures the programs of `bench/build_lanes.sh` (Isocron and the
hand-optimized fixed form in C with GCC and Clang, Rust and Zig, for
V = 16, 32, 64, with SSE4.2 only, AVX2 only or AVX-512) on an L1-resident and an
L2-resident input, with the protocol of `run.py` (calibrated repetitions,
interleaved runs, median, minimum, IQR). For every V, each output must be
bit-identical to the reference interpreter run with the same V.

Writes results/xeon-lanes.json and results/xeon-lanes.md.
Usage: bench/lanes.py [--quick] [--cpu N] [--name xeon-lanes]
"""

import argparse
import datetime
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import run  # noqa: E402
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mdstyle  # the marks of the verdicts (D235)

BIN = os.path.join(HERE, "bin-lanes")
SIZES = {"l1": 2048, "l2": 16384}
KERNELS = {"sum": ["a.f64"], "dot": ["a.f64", "b.f64"], "std_dev": ["a.f64"]}
LABELS = {"isc": "Isocron", "c-gcc": "C (GCC)", "c-clang": "C (Clang)", "rust": "Rust", "zig": "Zig"}
ORDER = ["isc", "c-gcc", "c-clang", "rust", "zig"]
LANES = [16, 32, 64]
ISAS = ["sse", "avx2", "avx512"]


def gen(size):
    d = os.path.join(run.DATA, "lanes-" + size)
    os.makedirs(d, exist_ok=True)
    n = SIZES[size]
    for name, seed in (("a.f64", 11), ("b.f64", 12)):
        p = os.path.join(d, name)
        if not os.path.exists(p) or os.path.getsize(p) != 8 * n:
            run.gen_f64(p, n, seed)
    return d


def programs(kernel):
    pat = re.compile(r"^(?P<impl>[a-z-]+)_%s_v(?P<v>\d+)_(?P<isa>sse|avx2|avx512)$" % kernel)
    out = []
    for name in sorted(os.listdir(BIN)):
        m = pat.match(name)
        if m:
            out.append({"bin": name, "impl": m.group("impl"), "v": int(m.group("v")), "isa": m.group("isa")})
    return out


def measure(args):
    os.makedirs(run.OUT, exist_ok=True)
    iscc = os.path.join(run.ROOT, "target", "release", "iscc")
    res = {"date": datetime.datetime.now().isoformat(timespec="seconds"), "host": run.machine_label(), "machine": run.machine(), "cpu": args.cpu,
           "protocol": {"warmup": args.warmup, "measures": args.measures}, "sizes": SIZES, "runs": {}}
    for size in SIZES:
        d = gen(size)
        res["runs"][size] = {}
        for kernel, files in KERNELS.items():
            inputs = [os.path.join(d, f) for f in files]
            refs = {}
            for v in LANES:
                refs[v] = os.path.join(run.OUT, "lanes_%s_%s_interp_v%d.f64" % (size, kernel, v))
                subprocess.run([iscc, "run", "--lanes", str(v), os.path.join(run.ROOT, "examples", "poc", kernel + ".isc")]
                               + inputs + [refs[v], "1"], check=True, capture_output=True)
            progs = programs(kernel)
            for p in progs:
                p["exe"] = os.path.join(BIN, p["bin"])
                p["out"] = os.path.join(run.OUT, "lanes_%s_%s.f64" % (size, p["bin"]))
                p["reps"] = run.calibrate(args.cpu, p["exe"], inputs, p["out"])
                p["samples"] = []
            for i in range(args.warmup + args.measures):
                k = i % len(progs)
                for p in progs[k:] + progs[:k]:
                    ns = run.run_once(args.cpu, p["exe"], inputs, p["out"], p["reps"])
                    if i >= args.warmup:
                        p["samples"].append(ns / p["reps"])
            rows = []
            for p in progs:
                q1, med, q3 = run.quartiles(p["samples"])
                check, rel = run.compare(p["out"], refs[p["v"]])
                rows.append({k: p[k] for k in ("bin", "impl", "v", "isa", "reps", "samples")} |
                            dict(median=med, q1=q1, q3=q3, iqr=q3 - q1, min=min(p["samples"]), check=check, rel=rel,
                                 ghz=run.effective_ghz(args.cpu, p["exe"], inputs, p["out"], p["reps"])))
                run.log("%-3s %-8s %-28s median %10.1f ns  min %10.1f  IQR %8.1f  %s" % (
                    size, kernel, p["bin"], med, min(p["samples"]), q3 - q1, check))
            res["runs"][size][kernel] = rows
    return res


def report(res, name="xeon-lanes"):
    m = res["machine"]
    L = []
    w = L.append
    fixed = m.get("governor") == "performance" and m.get("no_turbo") == "1"
    w("# Isocron — study of V (number of accumulators of the fixed reduction form)")
    w("")
    w("Generated by `bench/lanes.py` on %s, machine %s (%s). Raw data: `results/%s.json`." % (res["date"], run.host_label(res.get("host")), m.get("cpu"), name))
    w("")
    w("SPEC section 10 fixes V, the number of interleaved accumulators of the fixed reduction form (V = 32 since")
    w("this study; it was 16, provisional) and B = 4096 elements per block. This study measures V = 16, 32 and 64")
    w("with three instruction sets: SSE4.2 without AVX (`xmm` registers, 2 doubles, 16 registers: the code of the")
    w("Celeron J3455 of the POC, CPU `goldmont` for every compiler, run on this machine), AVX2 only (`ymm`, 4")
    w("doubles, 16 registers) and AVX-512 (`zmm`, 8 doubles, 32 registers), for Isocron (`iscc build --lanes V")
    w("--isa ...`) and for the hand-optimized fixed form in C (GCC, Clang), Rust and Zig built with the same V.")
    w("When the accumulators and the loaded elements do not fit in the registers, Isocron and the hand-optimized")
    w("references update the accumulators in several passes over each block, which does not change the result")
    w("(DECISIONS D56). Go has no SIMD and is left out. For each V, every output is compared bit for bit with the")
    w("reference interpreter run with the same V (`iscc run --lanes V`); results differ from one V to another,")
    w("which is why V belongs to the language and not to the compiler.")
    w("")
    w("Conditions: pinned to CPU %s; %s; %d interleaved measurements after %d warm-up measurements, each lasting at" % (
        res["cpu"], "fixed frequency (turbo off)" if fixed else
        "**frequency not fixed** (governor `%s`, turbo enabled: changing it was not permitted on this server), "
        "other processes not confined" % m.get("governor"), res["protocol"]["measures"], res["protocol"]["warmup"]))
    w("least 100 ms. Times are per call.")
    w("")
    for size, kernels in res["runs"].items():
        n = SIZES[size]
        for kernel, rows in kernels.items():
            w("## %s, %s (%d elements, %d KiB per array)" % (kernel, size.upper(), n, n * 8 // 1024))
            w("")
            w("Median time per call (minimum in parentheses). Best of each column in bold.")
            w("")
            cols = [(v, isa) for isa in ISAS for v in LANES if any((r["v"], r["isa"]) == (v, isa) for r in rows)]
            w("| Implementation | " + " | ".join("V=%d %s" % (v, isa.upper()) for v, isa in cols) + " |")
            w("|" + " --- |" * (len(cols) + 1))
            best = {c: min(r["median"] for r in rows if (r["v"], r["isa"]) == c) for c in cols}
            for impl in ORDER:
                cells = []
                for c in cols:
                    r = next((r for r in rows if r["impl"] == impl and (r["v"], r["isa"]) == c), None)
                    if r is None:
                        cells.append("—")
                        continue
                    t = "%s (%s)" % (run.fmt_ns(r["median"]), run.fmt_ns(r["min"]))
                    if r["median"] == best[c]:
                        t = "**%s**" % t
                    if r["check"] != "identical":
                        t += " ⚠ %s" % r["check"]
                    cells.append(t)
                w("| %s | %s |" % (LABELS[impl], " | ".join(cells)))
            w("")
            parts = []
            for isa in ISAS:
                base = next((r for r in rows if r["impl"] == "isc" and r["v"] == 16 and r["isa"] == isa), None)
                if base is None:
                    continue
                parts += ["%s V=%d %.2f×" % (isa.upper(), r["v"], r["median"] / base["median"])
                          for r in sorted((r for r in rows if r["impl"] == "isc" and r["isa"] == isa and r["v"] != 16),
                                          key=lambda r: r["v"])]
            w("Isocron relative to its own V = 16 with the same instruction set (lower is faster): " + ", ".join(parts) + ".")
            w("")
    bad = [r for ks in res["runs"].values() for rows in ks.values() for r in rows if r["check"] != "identical"]
    w("## Bit-exactness")
    w("")
    if bad:
        w("Outputs that differ from the interpreter with the same V:")
        for r in bad:
            w("* %s: %s (%.1e)" % (r["bin"], r["check"], r["rel"]))
    else:
        w("Every output (%d programs × 2 sizes) is bit-identical to the reference interpreter run with the same V." % (
            len(next(iter(next(iter(res["runs"].values())).values()))) * len(KERNELS)))
    w("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--cpu", type=int, default=int(os.environ.get("ISC_BENCH_CPU", "7")))
    ap.add_argument("--name", default="xeon-lanes")
    ap.add_argument("--report-only", action="store_true")
    args = ap.parse_args()
    args.warmup, args.measures = (1, 3) if args.quick else (run.WARMUP, run.MEASURES)
    os.makedirs(run.RESULTS, exist_ok=True)
    jpath = os.path.join(run.RESULTS, args.name + ".json")
    res = json.load(open(jpath)) if args.report_only else measure(args)
    if not args.report_only:
        json.dump(res, open(jpath, "w"), indent=1)
    open(os.path.join(run.RESULTS, args.name + ".md"), "w").write(mdstyle.verdicts(report(res, args.name)) + "\n")
    run.log("wrote", os.path.join(run.RESULTS, args.name + ".md"))


if __name__ == "__main__":
    main()
