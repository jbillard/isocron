#!/usr/bin/env python3
"""The table of `crates/isc-runtime-core/src/pow10_g.rs` (D467): for each k
from K_MIN to K_MAX, the 126 bits of 10^-k for Schubfach (R. Giulietti, "The
Schubfach way to render doubles"): with 10^-k = beta 2^r and
2^125 <= beta < 2^126, g = floor(beta) + 1, written as its high 63 bits and
its low 63 bits. Computed exactly with integers.
    tools/gen_pow10_rs.py > crates/isc-runtime-core/src/pow10_g.rs"""
from fractions import Fraction

K_MIN, K_MAX = -324, 292


def flog2pow10(e):
    return (e * 913124641741) >> 38


def main():
    print("// Generated by tools/gen_pow10_rs.py (D467): do not edit.")
    print("")
    print("/// For each k from -324 to 292, the high and low 63 bits of g, the 126")
    print("/// bits of 10^-k rounded up (Schubfach).")
    print("pub static POW10_G: [[u64; 2]; %d] = [" % (K_MAX - K_MIN + 1))
    for k in range(K_MIN, K_MAX + 1):
        v = Fraction(10) ** (-k)
        e = -k
        exact = (10 ** e).bit_length() - 1 if e >= 0 else -((10 ** -e).bit_length())
        assert exact == flog2pow10(e), (k, exact, flog2pow10(e))
        r = exact - 125
        beta = v / (Fraction(2) ** r)
        assert 2 ** 125 <= beta < 2 ** 126, k
        g = beta.numerator // beta.denominator + 1
        print("    [0x%016x, 0x%016x]," % (g >> 63, g & ((1 << 63) - 1)))
    print("];")


main()
