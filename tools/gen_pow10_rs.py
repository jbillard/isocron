#!/usr/bin/env python3
"""The table of `crates/isc-interp/src/pow10_g.rs` (D467): for each k
from K_MIN to K_MAX, the 126 bits of 10^-k for Schubfach (R. Giulietti, "The
Schubfach way to render doubles"): with 10^-k = beta 2^r and
2^125 <= beta < 2^126, g = floor(beta) + 1, written as its high 63 bits and
its low 63 bits. Computed exactly with integers.
    tools/gen_pow10_rs.py > crates/isc-interp/src/pow10_g.rs
With `--isc`, the same table as the function `$pow10G` of the prelude
(`crates/isc-types/src/prelude.isc`: the text between its two marks), the
high and the low bits of each g one after the other.
With `--isc-pow5`, the table of the function `$pow5T` of the prelude (the
reading of a float, between its two marks): for each q from Q_MIN to Q_MAX,
the 128 bits of 5^q that the algorithm of Eisel and Lemire multiplies by
(D. Lemire, "Number Parsing at a Gigabyte per Second"; the table of Rust's
`core::num::dec2flt`): the bits of 5^q from its highest one, cut, for
q >= 0; for q < 0, those of 2^b / 5^-q plus one, b the bits of 5^-q and 127
(down to -27) or twice its bits and 128 (below), cut to 128 bits. The high
64 bits, then the low 64."""
import sys
from fractions import Fraction

K_MIN, K_MAX = -324, 292


def flog2pow10(e):
    return (e * 913124641741) >> 38


def table():
    for k in range(K_MIN, K_MAX + 1):
        v = Fraction(10) ** (-k)
        e = -k
        exact = (10 ** e).bit_length() - 1 if e >= 0 else -((10 ** -e).bit_length())
        assert exact == flog2pow10(e), (k, exact, flog2pow10(e))
        r = exact - 125
        beta = v / (Fraction(2) ** r)
        assert 2 ** 125 <= beta < 2 ** 126, k
        g = beta.numerator // beta.denominator + 1
        yield g >> 63, g & ((1 << 63) - 1)


Q_MIN, Q_MAX = -342, 308


def table_pow5():
    for q in range(Q_MIN, Q_MAX + 1):
        if q < 0:
            power5 = 5 ** -q
            z = (power5 - 1).bit_length()
            assert (1 << z) >= power5 > (1 << (z - 1))
            if q >= -27:
                c = (1 << (z + 127)) // power5 + 1
            else:
                c = (1 << (2 * z + 128)) // power5 + 1
                while c >= 1 << 128:
                    c //= 2
        else:
            c = 5 ** q
            while c < 1 << 127:
                c *= 2
            while c >= 1 << 128:
                c //= 2
        assert 1 << 127 <= c < 1 << 128, q
        yield c >> 64, c & ((1 << 64) - 1)


def main():
    if sys.argv[1:] == ["--isc-pow5"]:
        print("// Generated by tools/gen_pow10_rs.py --isc-pow5: do not edit.")
        print("function $pow5T(q: i64): [u64, u64] {")
        print("    const t = [")
        print(",\n".join("        0x%016xu64, 0x%016xu64" % t for t in table_pow5()))
        print("    ];")
        print("    const i = (q + %d) * 2;" % -Q_MIN)
        print("    return [t[i], t[i + 1]];")
        print("}")
        print("// End of the generated table of the powers of five.")
        return
    if sys.argv[1:] == ["--isc"]:
        print("// Generated by tools/gen_pow10_rs.py --isc: do not edit.")
        print("function $pow10G(k: i64): [u64, u64] {")
        print("    const g = [")
        print(",\n".join("        0x%016xu64, 0x%016xu64" % g for g in table()))
        print("    ];")
        print("    const i = (k + %d) * 2;" % -K_MIN)
        print("    return [g[i], g[i + 1]];")
        print("}")
        print("// End of the generated table.")
        return
    print("// Generated by tools/gen_pow10_rs.py (D467): do not edit.")
    print("")
    print("/// For each k from -324 to 292, the high and low 63 bits of g, the 126")
    print("/// bits of 10^-k rounded up (Schubfach).")
    print("pub static POW10_G: [[u64; 2]; %d] = [" % (K_MAX - K_MIN + 1))
    for hi, lo in table():
        print("    [0x%016x, 0x%016x]," % (hi, lo))
    print("];")


main()
